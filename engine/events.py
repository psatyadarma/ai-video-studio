"""Events database tools. Source of truth: accounts/<acct>/knowledge/events.csv

  python3 -I engine/events.py render <knowledge_dir>              # regenerate events.md (readable view)
  python3 -I engine/events.py window <knowledge_dir> [days=14]    # print events in the last N days + upcoming
  python3 -I engine/events.py add <knowledge_dir> <json-file>     # append rows (list of dicts), assigns ids

Columns: id, date (YYYY-MM-DD, ranges as start), category (MKT ECO BIZ TECH POL NEWS ENV GLB),
event, key_numbers, storyline, status (verified|partial|upcoming), sources ("Label <url> ; ..."), added.
"""
import csv, datetime as dt, json, re, sys
from pathlib import Path

FIELDS = ["id", "date", "category", "event", "key_numbers", "storyline", "status", "sources", "added"]
CATS = {"MKT": "Markets", "ECO": "Economy & policy", "BIZ": "Business", "TECH": "Tech", "POL": "Politics & government",
        "NEWS": "National news", "ENV": "Environment & disasters", "GLB": "Global (Indonesia impact)"}


def load(k):
    with open(Path(k) / "events.csv", newline="") as f:
        return list(csv.DictReader(f))


def save(k, rows):
    rows.sort(key=lambda r: r["date"][:10])
    with open(Path(k) / "events.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for r in rows:
            w.writerow({x: r.get(x, "") for x in FIELDS})


def d(r):
    return dt.date.fromisoformat(r["date"][:10])


def links(s):
    return ", ".join(f"[{a.strip()}]({u})" for a, u in re.findall(r"([^;<]+)<([^>]+)>", s))


def render(k):
    rows = load(k)
    today = dt.date.today()
    recent = [r for r in rows if today - dt.timedelta(days=14) <= d(r) <= today]
    upcoming = [r for r in rows if d(r) > today]
    older = [r for r in rows if d(r) < today - dt.timedelta(days=14)]
    out = ["# Events database — Rangkumin Dong", "",
           f"Generated from `events.csv` on {today.isoformat()} · {len(rows)} events · do not edit this file by hand.", "",
           "## Upcoming", "", "| Date | Category | Event | Storyline |", "|---|---|---|---|"]
    out += [f"| {r['date']} | {CATS.get(r['category'], r['category'])} | {r['event']} | {r['storyline']} |" for r in upcoming]
    out += ["", "## Last 14 days, by category", ""]
    for c, name in CATS.items():
        rs = sorted([r for r in recent if r["category"] == c], key=d, reverse=True)
        if not rs:
            continue
        out += [f"### {name} ({len(rs)})", "", "| Date | Event | Key numbers | Storyline | Status | Sources |", "|---|---|---|---|---|---|"]
        out += [f"| {r['date']} | {r['event']} | {r['key_numbers']} | {r['storyline']} | {r['status']} | {links(r['sources'])} |" for r in rs]
        out.append("")
    if older:
        out += ["## Archive (older than 14 days)", "", "| Date | Category | Event |", "|---|---|---|"]
        out += [f"| {r['date']} | {r['category']} | {r['event']} |" for r in sorted(older, key=d, reverse=True)]
    (Path(k) / "events.md").write_text("\n".join(out) + "\n")
    print(f"rendered events.md: {len(recent)} recent, {len(upcoming)} upcoming, {len(older)} archived")


def window(k, days=14):
    today = dt.date.today()
    for r in sorted(load(k), key=d):
        if d(r) >= today - dt.timedelta(days=days):
            print(f"{r['id']} {r['date']} {r['category']:4} [{r['status']}] {r['event']} | {r['key_numbers']} | {r['storyline']}")


def add(k, path):
    rows = load(k)
    n = max([int(r["id"][1:]) for r in rows] or [0])
    for item in json.loads(Path(path).read_text()):
        n += 1
        item.setdefault("added", dt.date.today().isoformat())
        item["id"] = f"E{n:04d}"
        rows.append(item)
    save(k, rows)
    print("total", len(rows))


if __name__ == "__main__":
    cmd, k = sys.argv[1], sys.argv[2]
    {"render": lambda: render(k), "window": lambda: window(k, int(sys.argv[3]) if len(sys.argv) > 3 else 14),
     "add": lambda: add(k, sys.argv[3])}[cmd]()
